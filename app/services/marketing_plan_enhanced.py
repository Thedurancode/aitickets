def clean_text_for_pdf(text: str) -> str:
    """Remove emojis and special unicode characters that can't be rendered in PDF."""
    return re.sub(r'[^\x00-\xFF]+', '', text).strip()


class EnhancedMarketingPlanPDF(FPDF):
    """World-class PDF with charts, graphs, and advanced analytics."""

    def __init__(self):
        super().__init__()
        self.set_auto_page_break(auto=True, margin=15)
        self.brand_color = (41, 128, 185)  # Primary blue
        self.success_color = (46, 204, 113)  # Green
        self.warning_color = (241, 196, 15)  # Yellow
